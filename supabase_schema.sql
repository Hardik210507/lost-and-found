-- ===================================================================
-- Supabase PostgreSQL Schema for Lost and Found System
-- Run this in your Supabase Dashboard: SQL Editor -> New Query -> Run
-- ===================================================================

-- 1. Items Table
CREATE TABLE IF NOT EXISTS item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type VARCHAR(50) NOT NULL, -- 'LOST' or 'FOUND'
    title VARCHAR(255) NOT NULL,
    description TEXT,
    category VARCHAR(100),
    location VARCHAR(100),
    status VARCHAR(50) DEFAULT 'PENDING', -- 'PENDING', 'MATCHED', 'RESOLVED'
    image_path TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    posted_by VARCHAR(255)
);

-- 2. Claims Table
CREATE TABLE IF NOT EXISTS claim (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT REFERENCES item(id) ON DELETE CASCADE,
    claimant VARCHAR(255) NOT NULL,
    identifying_detail TEXT NOT NULL,
    status VARCHAR(50) DEFAULT 'PENDING' -- 'PENDING', 'APPROVED', 'REJECTED'
);

-- 3. Item Matches Table
CREATE TABLE IF NOT EXISTS item_match (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT REFERENCES item(id) ON DELETE CASCADE,
    matched_item_id BIGINT REFERENCES item(id) ON DELETE CASCADE,
    score INTEGER DEFAULT 0
);

-- 4. Notifications Table
CREATE TABLE IF NOT EXISTS notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message TEXT NOT NULL,
    is_read BOOLEAN DEFAULT FALSE
);

-- 5. Users Table (Authentication & Roles)
CREATE TABLE IF NOT EXISTS app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'USER', -- 'USER' (Student) or 'ADMIN'
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

